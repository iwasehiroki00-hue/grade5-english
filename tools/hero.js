function gear(lv){
  return {
    weapon: lv>=10?'legend':lv>=8?'steel':lv>=5?'iron':lv>=3?'copper':lv>=2?'stick':null,
    shield: lv>=10?'dragon':lv>=9?'magic':lv>=7?'steel':lv>=5?'iron':lv>=3?'leather':null,
    armor:  lv>=10?'gold':lv>=9?'magic':lv>=7?'steel':lv>=6?'chain':lv>=4?'leather':'tshirt',
    helm:   lv>=10?'king':lv>=9?'wing':lv>=7?'iron':null,
    cape:   lv>=10?'royal':lv>=8?'red':null
  };
}
var GN={
  weapon:{stick:'ひのきのぼう',copper:'どうのつるぎ',iron:'てつのつるぎ',steel:'はがねのつるぎ',legend:'でんせつのつるぎ'},
  shield:{leather:'かわのたて',iron:'てつのたて',steel:'はがねのたて',magic:'まほうのたて',dragon:'ドラゴンのたて'},
  armor:{tshirt:'Tシャツとたんパン',leather:'かわのよろい',chain:'くさりかたびら',steel:'はがねのよろい',magic:'まほうのよろい',gold:'おうごんのよろい'},
  helm:{iron:'てつのかぶと',wing:'はねかぶと',king:'おうのかぶと'},
  cape:{red:'ゆうしゃのマント',royal:'おうのマント'}
};
function heroSvg(lv){
  var g=gear(lv), s='';
  function R(x,y,w,h,c){ s+='<rect x="'+x+'" y="'+y+'" width="'+w+'" height="'+h+'" fill="'+(PAL[c]||c)+'"/>'; }
  var A=g.armor, S=g.shield, H=g.helm, W=g.weapon, C=g.cape;

  /* マント（体の後ろ） */
  if(C==='red'){ R(7,17,26,18,'r'); R(7,17,26,2,'R'); R(7,33,26,2,'R'); R(7,19,1,14,'R'); R(32,19,1,14,'R'); }
  if(C==='royal'){ R(6,17,28,19,'P'); R(6,17,28,2,'t'); R(6,34,28,2,'t'); R(6,19,1,15,'t'); R(33,19,1,15,'t'); }

  /* 頭 */
  R(14,4,12,5,'N');            // 髪
  R(13,6,1,4,'N'); R(26,6,1,4,'N'); // もみあげ
  R(14,8,12,8,'s');            // 顔
  R(15,9,1,1,'N'); R(19,8,1,1,'N'); R(23,9,1,1,'N'); // 前髪のギザ
  R(17,11,2,2,'k'); R(21,11,2,2,'k'); // 目
  R(19,14,2,1,'R');            // 口
  R(18,16,4,2,'s');            // 首

  /* 腕（肌） */
  R(9,18,4,9,'s'); R(27,18,4,9,'s');

  /* 胴・袖・ズボン */
  if(A==='tshirt'){
    R(13,18,14,10,'w'); R(9,18,4,3,'w'); R(27,18,4,3,'w');
    R(19,21,2,3,'r'); R(18,22,4,1,'r');           // 胸の赤いマーク
    R(13,28,14,6,'B');                             // 紺の短パン
  }else if(A==='leather'){
    R(13,18,14,10,'n'); R(9,18,4,3,'n'); R(27,18,4,3,'n');
    R(13,26,14,2,'N'); R(19,26,2,2,'t');           // ベルト・バックル
    R(14,19,1,7,'N'); R(25,19,1,7,'N');            // 縫い目
    R(13,28,14,6,'N');
  }else if(A==='chain'){
    R(13,18,14,10,'e'); R(9,18,4,3,'e'); R(27,18,4,3,'e');
    for(var yy=19;yy<26;yy++) for(var xx=14;xx<27;xx++) if((xx+yy)%2===0) R(xx,yy,1,1,'E');
    R(13,26,14,2,'N'); R(19,26,2,2,'t');
    R(13,28,14,6,'E');
  }else if(A==='steel'){
    R(13,18,14,10,'e'); R(9,18,4,3,'e'); R(27,18,4,3,'e');
    R(15,19,2,7,'w'); R(24,19,1,7,'E');            // ハイライト・影
    R(8,17,6,4,'E'); R(26,17,6,4,'E'); R(9,18,4,1,'e'); R(27,18,4,1,'e'); // 肩パッド
    R(13,26,14,2,'E'); R(13,28,14,6,'E');
  }else if(A==='magic'){
    R(13,18,14,10,'b'); R(9,18,4,3,'b'); R(27,18,4,3,'b');
    R(15,19,2,7,'c'); R(24,19,1,7,'B');
    R(19,21,2,2,'w'); R(18,22,4,1,'c');            // 胸の光
    R(8,17,6,4,'B'); R(26,17,6,4,'B'); R(9,18,4,1,'c'); R(27,18,4,1,'c');
    R(13,26,14,2,'B'); R(13,28,14,6,'B');
  }else if(A==='gold'){
    R(13,18,14,10,'y'); R(9,18,4,3,'y'); R(27,18,4,3,'y');
    R(15,19,2,7,'w'); R(24,19,1,7,'t'); R(13,25,14,1,'t');
    R(19,21,2,2,'r'); R(18,22,4,1,'r'); R(19,20,2,1,'R'); // 赤い宝石
    R(8,17,6,4,'t'); R(26,17,6,4,'t'); R(9,18,4,1,'y'); R(27,18,4,1,'y');
    R(13,26,14,2,'t'); R(13,28,14,6,'t');
  }

  /* 手 */
  R(9,27,4,3,'s'); R(27,27,4,3,'s');

  /* 足・靴 */
  var leg = (A==='tshirt'||A==='leather') ? 's' : (A==='gold'?'t':A==='magic'?'B':'E');
  R(14,34,5,8,leg); R(21,34,5,8,leg);
  if(A==='tshirt'||A==='leather'){ R(13,42,6,3,'N'); R(21,42,6,3,'N'); }
  else { R(13,41,6,4,A==='gold'?'t':A==='magic'?'B':'E'); R(21,41,6,4,A==='gold'?'t':A==='magic'?'B':'E'); R(13,44,6,1,'k'); R(21,44,6,1,'k'); }

  /* かぶと */
  if(H==='iron'){ R(13,3,14,6,'e'); R(14,2,12,1,'e'); R(13,8,14,1,'E'); R(15,4,2,3,'w'); }
  if(H==='wing'){ R(13,3,14,6,'c'); R(14,2,12,1,'c'); R(13,8,14,1,'b'); R(15,4,2,3,'w');
    R(10,5,3,2,'w'); R(9,3,2,3,'w'); R(27,5,3,2,'w'); R(29,3,2,3,'w'); }
  if(H==='king'){ R(13,3,14,6,'t'); R(14,2,12,1,'t'); R(13,8,14,1,'N'); R(15,4,2,3,'y');
    R(18,0,4,3,'r'); R(19,-1,2,2,'r'); R(16,1,2,2,'y'); R(22,1,2,2,'y'); R(19,5,2,2,'c'); }

  /* 盾（左手の前） */
  if(S==='leather'){ R(3,19,10,12,'N'); R(4,20,8,10,'n'); R(5,19,6,1,'N'); R(5,31,6,1,'N'); R(7,24,2,2,'N'); }
  if(S==='iron'){ R(3,18,10,13,'E'); R(4,19,8,11,'e'); R(5,20,2,2,'w'); }
  if(S==='steel'){ R(3,18,10,13,'E'); R(4,19,8,11,'e'); R(7,20,2,9,'r'); R(4,24,8,2,'r'); R(5,20,1,2,'w'); }
  if(S==='magic'){ R(3,18,10,13,'c'); R(4,19,8,11,'b'); R(7,21,2,1,'y'); R(6,22,4,1,'y'); R(7,23,2,1,'y'); R(6,24,1,1,'y'); R(9,24,1,1,'y'); R(5,25,1,1,'y'); R(10,25,1,1,'y'); }
  if(S==='dragon'){ R(3,18,10,13,'t'); R(4,19,8,11,'R'); R(5,20,6,9,'r'); R(6,21,4,2,'y'); R(7,23,2,5,'y'); R(5,25,1,2,'y'); R(10,25,1,2,'y'); }

  /* 武器（右手。最後に描く） */
  var ws='';
  function WR(x,y,w,h,c){ ws+='<rect x="'+x+'" y="'+y+'" width="'+w+'" height="'+h+'" fill="'+(PAL[c]||c)+'"/>'; }
  if(W==='stick'){ WR(28,12,2,19,'n'); WR(28,12,1,19,'N'); }
  if(W==='copper'){ WR(28,10,3,15,'o'); WR(28,10,1,15,'y'); WR(28,8,3,2,'o'); WR(25,25,9,2,'t'); WR(28,27,3,4,'N'); WR(28,31,3,1,'t'); }
  if(W==='iron'){ WR(28,6,3,19,'e'); WR(28,6,1,19,'w'); WR(28,4,3,2,'e'); WR(29,3,1,1,'e'); WR(25,25,9,2,'E'); WR(28,27,3,4,'N'); WR(28,31,3,1,'E'); }
  if(W==='steel'){ WR(27,2,4,23,'e'); WR(27,2,1,23,'w'); WR(28,0,2,2,'e'); WR(24,25,11,2,'t'); WR(25,24,9,1,'t'); WR(28,27,3,4,'N'); WR(28,31,3,1,'t'); }
  if(W==='legend'){ WR(27,-1,4,26,'y'); WR(27,-1,1,26,'w'); WR(28,-1,2,3,'w'); WR(30,2,1,20,'t'); WR(24,25,11,2,'t'); WR(25,24,9,1,'t'); WR(23,25,1,2,'y'); WR(35,25,1,2,'y'); WR(28,27,3,4,'P'); WR(28,24,3,1,'r'); WR(28,31,3,1,'t'); }
  if(ws) s+='<g class="wpn'+(W==='legend'?' glow':'')+'">'+ws+'</g>';

  return '<svg viewBox="0 0 40 48" xmlns="http://www.w3.org/2000/svg" shape-rendering="crispEdges" overflow="visible">'+s+'</svg>';
}
